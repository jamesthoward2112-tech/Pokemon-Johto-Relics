#!/usr/bin/env python3
"""Inventory all active PJR HNS maps' story and Relic dialogue for PRU continuity.

Output is a transparent, machine-generated source audit, *not* gameplay sign-off.
"""
import csv
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAPS = ROOT / "data" / "maps"
SCRIPTS = sorted(MAPS.glob("*_hns/scripts.inc"))
OTHER = sorted(MAPS.glob("*_F rlg/scripts.inc"))  # deliberately never treated as live HNS
KEYWORDS = (
    "relic", "resonance", "alph", "legendary", "ancient", "ho-oh", "ho_oh",
    "rainbow crest", "champion", "rocket", "giovanni", "hoenn", "kanto",
    "starter", "egg", "prof.oak", "prof.elm", "prof.birch", "mewtwo",
    "celebi", "jirachi", "lugia", "suicune", "entei", "raikou",
    "arceus", "unown", "sinjoh", "tin tower", "bell tower",
)
RARE_CONFLICTS = (
    ("prior-game travel", r"(?i)you (?:returned|came|traveled|travelled|sailed|visited) (?:here )?from HOENN"),
    ("multi-ROM history", r"(?i)(?:your|the) (?:previous|last) (?:game|ROM|region|playthrough)"),
    ("old starter choice", r"(?i)(?:you didn't choose|choose one of (?:three|these) pok[eé]mon|left POK[eé] BALL.*PIKACHU)"),
    ("Kanto-to-Hoenn save transition", r"(?i)(?:donat(?:e|ed|ing) .*TRAINING SCHOOL|stored your KANTO POK[eé]MON.*HOENN)"),
)
data = []
candidates = []
flag_ledger = defaultdict(lambda: defaultdict(list))
matches_by_map = defaultdict(Counter)
text_records = []
for path in SCRIPTS:
    lines = path.read_text(errors="replace").splitlines()
    map_name = path.parent.name
    label = ""
    for number, raw in enumerate(lines, start=1):
        stripped = raw.strip()
        if stripped and not stripped.startswith("@") and re.fullmatch(r"[A-Za-z0-9_]+:{1,2}", stripped):
            label = stripped.rstrip(":")
        if stripped.startswith("@"): continue
        for flag in re.findall(r"FLAG_PJR_RELIC_[A-Z0-9_]+|FLAG_PJR_GOT_RAINBOW_CREST|FLAG_IS_CHAMPION|FLAG_IS_KANTO_CHAMPION", raw):
            op = re.search(r"\b(goto_if_[a-z]+|call_if_[a-z]+|setflag|clearflag)\b", raw)
            if op: flag_ledger[flag][op.group(1)].append(f"{map_name}:{number}")
        for tag, regex in RARE_CONFLICTS:
            if re.search(regex, raw): candidates.append((map_name, number, label, tag, stripped))
        if ".string " not in raw or raw.lstrip().startswith("@"): continue
        text = re.search(r'\.string\s+"(.*)"', raw)
        if not text: continue
        val = text.group(1)
        present = tuple(k for k in KEYWORDS if k in val.lower())
        if not present: continue
        for keyword in present: matches_by_map[map_name][keyword] += 1
        data.append((map_name, number, label, ", ".join(present), val))
        text_records.append((map_name, number, label, val))

with (ROOT / "PRU-Relic-Dialogue-Live-HNS-Inventory.csv").open("w", newline="", encoding="utf-8") as fh:
    writer = csv.writer(fh)
    writer.writerow(("map", "source line", "script label", "keywords", "dialogue source"))
    writer.writerows(data)

lines_out = [
    "# PRU — All active HNS maps: Relic/story dialogue source inventory",
    "",
    "Automatically generated by the GitHub Actions runner. **This is complete enumeration for the stated lexical keywords only, not a full semantic dialogue review or emulator pass.**",
    "",
    f"- Scanned active map directories: **{len(SCRIPTS)}**",
    f"- Maps with keyword-matched dialogue: **{len(matches_by_map)}**",
    f"- Source dialogue lines matched: **{len(data)}**",
    f"- Obsolete/sequel-pattern candidate hits: **{len(candidates)}**",
    "",
    "## Candidate continuity contradictions requiring manual review",
]
if candidates:
    lines_out += [f"- `{name}:{num}` (`{label}`) — {tag}: `{raw}`" for name, num, label, tag, raw in candidates]
else:
    lines_out.append("- None of the explicitly recognised phrase patterns were found in active HNS dialogue source.")
lines_out += ["", "## Coverage by town / map and theme", "", "| Active map | Relic | Resonance | Legendary | Championship | Kanto/Hoenn | Other ancient/story |", "|---|---:|---:|---:|---:|---:|---:|"]
for name in sorted(matches_by_map):
    c = matches_by_map[name]
    others = sum(v for k,v in c.items() if k not in ("relic","resonance","legendary","champion","kanto","hoenn"))
    lines_out.append(f"| `{name}` | {c['relic']} | {c['resonance']} | {c['legendary']} | {c['champion']} | {c['kanto']+c['hoenn']} | {others} |")
lines_out += ["", "## Critical plot flag references (source evidence, not runtime proof)", ""]
for flag in sorted(flag_ledger):
    parts=[]
    for op, refs in sorted(flag_ledger[flag].items()):
        parts.append(f"{op} ({len(refs)}) at " + ", ".join(refs[:12]) + ("…" if len(refs)>12 else ""))
    lines_out.append(f"- **`{flag}`**: " + "; ".join(parts))
lines_out += [
    "", "## Known PJR narrative/event-state risks detected from the current source",
    "",
    "- The post-first-Hall-of-Fame re-clear route can mark a Kanto championship without a confirmed Kanto badge count; review Lance dialogue and flags with four-tier champion design.",
    "- Some existing Hall-of-Fame replay scripts clear previously caught legendary flags and respawn roamer/static encounters; guard one-time grants and catch states.",
    "- Red's Ancient Rainbow Crest grant does not currently verify that the bag accepted the item before setting the obtained flag.",
    "- Legendary encounters and post-capture retries require full emulator testing. Do not mark narrative complete from static checks.",
    "",
    "## Sign-off gates",
    "",
    "- [ ] Manually review candidate source paragraphs and indirect donor map conversions; audit inventory CSV against chosen active maps.",
    "- [ ] Verify all historic Rocket dialogue and Kanto donor scenes cannot resurrect a disbanded Giovanni organisation.",
    "- [ ] Prove every seven-rel ic + Ho-Oh state and all side legendary states in save/emulator flows.",
    "- [ ] Finish accessibility, text paging and dialogue rendering tests in the built ROM.",
]
(ROOT / "PRU-Relic-Dialogue-Live-HNS-Inventory.md").write_text("\n".join(lines_out)+"\n",encoding="utf-8")
print(f"SCANNED: {len(SCRIPTS)} live HNS maps, {len(matches_by_map)} with keyword dialogue, {len(data)} lines.")
print(f"FLAG LEDGER: {len(flag_ledger)} key Relic and league flags.")
print(f"CONTINUITY CANDIDATES: {len(candidates)}")
for x in candidates[:25]:
    print("MANUAL REVIEW:", x)
print("EXPORT: PRU-Relic-Dialogue-Live-HNS-Inventory.md and .csv")
